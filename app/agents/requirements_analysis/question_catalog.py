# ============================================================
# CATALOG HELPERS
# ============================================================

def get_question_catalog() -> tuple[dict[str, Any], ...]:
    return QUESTION_CATALOG


def get_question_by_id(
    question_id: str,
) -> dict[str, Any] | None:

    return next(
        (
            question
            for question in QUESTION_CATALOG
            if question["question_id"] == question_id
        ),
        None,
    )


def get_required_questions() -> list[dict[str, Any]]:

    return [
        question
        for question in QUESTION_CATALOG
        if question["required"]
    ]


def get_question_sequence() -> list[str]:

    return [
        question["question_id"]
        for question in QUESTION_CATALOG
    ]
